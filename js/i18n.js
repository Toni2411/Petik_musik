let lang = "en";

export function detectLang() {
  try {
    const saved = localStorage.getItem("petik.lang");
    if (saved === "en" || saved === "id") return saved;
  } catch {}
  return (navigator.language || "").toLowerCase().startsWith("id") ? "id" : "en";
}

export function setLang(l) {
  lang = l;
  try { localStorage.setItem("petik.lang", l); } catch {}
  document.documentElement.lang = l;
  for (const el of document.querySelectorAll("[data-i18n]")) el.textContent = t(el.dataset.i18n);
  for (const el of document.querySelectorAll("[data-i18n-ph]")) el.placeholder = t(el.dataset.i18nPh);
  for (const el of document.querySelectorAll("[data-lang]")) el.classList.toggle("on", el.dataset.lang === l);
}

/** Translate; "{n}" style placeholders are filled from vars. */
export const t = (key, vars) => {
  let s = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, v);
  return s;
};
export const getLang = () => lang;
